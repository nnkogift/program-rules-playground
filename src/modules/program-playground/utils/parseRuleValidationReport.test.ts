import v240InvalidValue from './__fixtures__/validationReport.v2_40.errorInvalidValue.json'
import v240ShowError from './__fixtures__/validationReport.v2_40.errorShowError.json'
import v243InvalidValue from './__fixtures__/validationReport.v2_43.errorInvalidValue.json'
import v243Ok from './__fixtures__/validationReport.v2_43.ok.json'
import v243ShowError from './__fixtures__/validationReport.v2_43.errorShowError.json'
import { parseRuleValidationReport } from './parseRuleValidationReport'

const RULE_ID = 'dahuKlP7jR2'
const SHOWERROR_RULE = new Map([[RULE_ID, ['SHOWERROR']]])

// Synthetic reports for codes the play instances did not produce.
const report = (
    errorReports: unknown[] = [],
    warningReports: unknown[] = []
) => ({ validationReport: { errorReports, warningReports } })

const ruleMessage = (ruleId: string, text: string) =>
    `Generated by ProgramRule (\`${ruleId}\`) - \`${text}\``

const parse = (
    body: unknown,
    status: 'ACTIVE' | 'COMPLETED' = 'ACTIVE',
    actionTypesByRule?: ReadonlyMap<string, readonly string[]>
) => parseRuleValidationReport(body, { status, actionTypesByRule })

describe('parseRuleValidationReport with real play reports', () => {
    it.each([
        ['2.40', v240ShowError],
        ['2.43', v243ShowError],
    ])('attributes a SHOWERROR report to its rule on %s', (_version, body) => {
        const { verification, otherErrors } = parse(
            body,
            'ACTIVE',
            SHOWERROR_RULE
        )

        expect(otherErrors).toEqual([])
        expect(verification.entries).toEqual([
            expect.objectContaining({
                ruleId: RULE_ID,
                actionType: 'SHOWERROR',
                level: 'ERROR',
                targetId: 'vANAXwtLwcT',
            }),
        ])
    })

    it('keeps SHOWERROR when completing, since the server reports it identically', () => {
        const { entries } = parse(
            v243ShowError,
            'COMPLETED',
            SHOWERROR_RULE
        ).verification

        expect(entries[0].actionType).toBe('SHOWERROR')
    })

    it('uses ERRORONCOMPLETE when the rule only declares that action', () => {
        const { entries } = parse(
            v243ShowError,
            'COMPLETED',
            new Map([[RULE_ID, ['ERRORONCOMPLETE']]])
        ).verification

        expect(entries[0].actionType).toBe('ERRORONCOMPLETE')
    })

    it('breaks a tie between both declared actions with the event status', () => {
        const both = new Map([[RULE_ID, ['SHOWERROR', 'ERRORONCOMPLETE']]])

        expect(
            parse(v243ShowError, 'ACTIVE', both).verification.entries[0]
                .actionType
        ).toBe('SHOWERROR')
        expect(
            parse(v243ShowError, 'COMPLETED', both).verification.entries[0]
                .actionType
        ).toBe('ERRORONCOMPLETE')
    })

    it.each([
        ['2.40', v240InvalidValue],
        ['2.43', v243InvalidValue],
    ])('lists an E1302 as another import error on %s', (_version, body) => {
        const { verification, otherErrors } = parse(body)

        expect(verification.entries).toEqual([])
        expect(otherErrors).toEqual([
            expect.objectContaining({ code: 'E1302' }),
        ])
    })

    it('reads the body the data engine puts on the thrown error, as seen for E1029', () => {
        // Real 2.43.2 response: root org unit not assigned to the program.
        const error = {
            details: {
                status: 'ERROR',
                validationReport: {
                    errorReports: [
                        {
                            errorCode: 'E1029',
                            message:
                                'Event OrganisationUnit: `ImspTQPwCqd` and Program: `lxAQ7Zs9VYR`, do not match.',
                            trackerType: 'EVENT',
                            uid: 'bqCthcalG2W',
                        },
                    ],
                    warningReports: [],
                },
            },
        }

        expect(parse(error).otherErrors).toEqual([
            expect.objectContaining({ code: 'E1029' }),
        ])
    })

    it('returns nothing for a clean dry run', () => {
        expect(parse(v243Ok)).toEqual({
            verification: { entries: [] },
            otherErrors: [],
        })
    })

    it('reads the report from the thrown 409 error shape', () => {
        const { entries } = parse(
            { details: { response: v243ShowError } },
            'ACTIVE',
            SHOWERROR_RULE
        ).verification

        expect(entries).toHaveLength(1)
    })
})

describe('parseRuleValidationReport with synthetic reports', () => {
    it('maps a rule warning to SHOWWARNING', () => {
        const { entries } = parse(
            report(
                [],
                [
                    {
                        errorCode: 'E1300',
                        message: ruleMessage('abcdefghij2', 'y'),
                    },
                ]
            )
        ).verification

        expect(entries[0]).toMatchObject({
            actionType: 'SHOWWARNING',
            level: 'WARNING',
        })
    })

    it.each(['E1301', 'E1306'])('maps %s to a mandatory error', (errorCode) => {
        const { entries } = parse(
            report([{ errorCode, message: ruleMessage('abcdefghij1', 'm') }])
        ).verification

        expect(entries[0]).toMatchObject({
            actionType: 'SETMANDATORYFIELD',
            level: 'ERROR',
        })
    })

    it('maps assign conflicts to errors and overwrites to warnings', () => {
        const { entries } = parse(
            report(
                [
                    {
                        errorCode: 'E1307',
                        message: ruleMessage('abcdefghij1', 'a'),
                    },
                ],
                [
                    {
                        errorCode: 'E1308',
                        message: ruleMessage('abcdefghij2', 'b'),
                    },
                ]
            )
        ).verification

        expect(entries.map((entry) => [entry.actionType, entry.level])).toEqual(
            [
                ['ASSIGN', 'ERROR'],
                ['ASSIGN', 'ASSIGN_OVERWRITE'],
            ]
        )
    })

    it.each(['E1319', 'E1320', 'E1321', 'E1322'])(
        'maps %s to SCHEDULEEVENT',
        (errorCode) => {
            const { entries } = parse(
                report([
                    { errorCode, message: ruleMessage('abcdefghij1', 's') },
                ])
            ).verification

            expect(entries[0].actionType).toBe('SCHEDULEEVENT')
        }
    )

    it('treats a rule code without a parsable rule id as another error', () => {
        const { verification, otherErrors } = parse(
            report([{ errorCode: 'E1300', message: 'no rule here' }])
        )

        expect(verification.entries).toEqual([])
        expect(otherErrors).toHaveLength(1)
    })

    it('returns an empty result for unrelated bodies', () => {
        expect(parse(undefined)).toEqual({
            verification: { entries: [] },
            otherErrors: [],
        })
    })
})
