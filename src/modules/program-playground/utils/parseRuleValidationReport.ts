import type {
    ServerReportEntry,
    ServerReportLevel,
    ServerVerification,
} from '@nnkogift/dhis2-form-utils-devtools'
import { ProgramRuleActionType } from '@nnkogift/dhis2-form-utils-metadata'
import { z } from 'zod'
import type { EventStatus } from '@/modules/program-playground/utils/trackerPayloads'

// 2.40 words it "program rule (`uid`)", 2.43 "ProgramRule (`uid`)".
const RULE_ID_PATTERN = /Generated by program ?rule \(`?([A-Za-z0-9]{11})`?\)/i
// SHOWERROR/SHOWWARNING messages end with the target field: "... (uid)".
const TRAILING_TARGET_PATTERN = /\(([A-Za-z0-9]{11})\)`?\.?$/
// SETMANDATORYFIELD names it instead: "Mandatory Attribute `uid` is not present".
const MANDATORY_TARGET_PATTERN =
    /Mandatory (?:Attribute|DataElement|Data element) `?([A-Za-z0-9]{11})`?/i
const RULE_ERROR_CODE_MIN = 1300
const RULE_ERROR_CODE_MAX = 1322

const reportItemSchema = z.object({
    message: z.string().optional(),
    errorCode: z.string().optional(),
    uid: z.string().optional(),
})

const validationReportSchema = z.object({
    errorReports: z.array(reportItemSchema).optional(),
    warningReports: z.array(reportItemSchema).optional(),
})

const reportContainerSchema = z.object({
    validationReport: validationReportSchema.optional(),
    response: z
        .object({ validationReport: validationReportSchema.optional() })
        .optional(),
    details: z
        .object({
            validationReport: validationReportSchema.optional(),
            response: z
                .object({ validationReport: validationReportSchema.optional() })
                .optional(),
        })
        .optional(),
})

type ReportItem = z.infer<typeof reportItemSchema>

export type OtherImportError = {
    code?: string
    message: string
}

export type ParsedRuleValidationReport = {
    verification: ServerVerification
    otherErrors: OtherImportError[]
}

const ReportKind = {
    ERROR: 'ERROR',
    WARNING: 'WARNING',
} as const
type ReportKind = (typeof ReportKind)[keyof typeof ReportKind]

type MappingContext = {
    kind: ReportKind
    status: EventStatus
    /** The reporting rule's declared action types, when known. */
    ruleActionTypes: readonly string[]
}

type ActionMapping = (context: MappingContext) => {
    actionType: string
    level: ServerReportLevel
}

const SHOW_MESSAGE_ACTIONS = {
    [ReportKind.ERROR]: {
        immediate: ProgramRuleActionType.SHOWERROR,
        onComplete: ProgramRuleActionType.ERRORONCOMPLETE,
    },
    [ReportKind.WARNING]: {
        immediate: ProgramRuleActionType.SHOWWARNING,
        onComplete: ProgramRuleActionType.WARNINGONCOMPLETE,
    },
} as const

// E1300 is the same report for the immediate and on-complete variants, so the
// rule's own actions decide; the event status only breaks a tie.
const showMessage: ActionMapping = ({ kind, status, ruleActionTypes }) => {
    const { immediate, onComplete } = SHOW_MESSAGE_ACTIONS[kind]
    const declared = [immediate, onComplete].filter((type) =>
        ruleActionTypes.includes(type)
    )
    const preferred = status === 'COMPLETED' ? onComplete : immediate
    const actionType =
        declared.length === 1
            ? declared[0]
            : declared.includes(preferred)
              ? preferred
              : immediate
    return {
        actionType,
        level: kind === ReportKind.ERROR ? 'ERROR' : 'WARNING',
    }
}

const mandatory: ActionMapping = () => ({
    actionType: ProgramRuleActionType.SETMANDATORYFIELD,
    level: 'ERROR',
})

// A rejected assign is an error; an allowed overwrite comes back as a warning.
const assign: ActionMapping = ({ kind }) => ({
    actionType: ProgramRuleActionType.ASSIGN,
    level: kind === ReportKind.ERROR ? 'ERROR' : 'ASSIGN_OVERWRITE',
})

const invalidDate: ActionMapping = () => ({
    actionType: ProgramRuleActionType.SCHEDULEEVENT,
    level: 'ERROR',
})

const scheduleEvent: ActionMapping = ({ kind }) => ({
    actionType: ProgramRuleActionType.SCHEDULEEVENT,
    level: kind === ReportKind.ERROR ? 'ERROR' : 'WARNING',
})

const ACTION_BY_ERROR_CODE: Record<string, ActionMapping> = {
    E1300: showMessage,
    E1301: mandatory,
    E1306: mandatory,
    E1307: assign,
    E1308: assign,
    E1309: assign,
    E1310: assign,
    E1319: invalidDate,
    E1320: scheduleEvent,
    E1321: scheduleEvent,
    E1322: scheduleEvent,
}

function isRuleErrorCode(code: string): boolean {
    const numeric = Number(code.slice(1))
    return (
        numeric >= RULE_ERROR_CODE_MIN &&
        numeric <= RULE_ERROR_CODE_MAX &&
        code.startsWith('E')
    )
}

/**
 * The importer returns the report on success and, for VALIDATE with errors,
 * inside the thrown 409; both shapes are accepted.
 */
function findValidationReport(
    body: unknown
): z.infer<typeof validationReportSchema> | undefined {
    const parsed = reportContainerSchema.safeParse(body)
    if (!parsed.success) {
        return undefined
    }
    return (
        parsed.data.validationReport ??
        parsed.data.response?.validationReport ??
        parsed.data.details?.validationReport ??
        parsed.data.details?.response?.validationReport
    )
}

function toEntry(
    item: ReportItem,
    kind: ReportKind,
    options: ParseOptions
): ServerReportEntry | undefined {
    const { errorCode, message } = item
    if (!errorCode || !message || !isRuleErrorCode(errorCode)) {
        return undefined
    }
    const ruleId = RULE_ID_PATTERN.exec(message)?.[1]
    const mapping = ACTION_BY_ERROR_CODE[errorCode]
    if (!ruleId || !mapping) {
        return undefined
    }
    return {
        ruleId,
        ...mapping({
            kind,
            status: options.status,
            ruleActionTypes: options.actionTypesByRule?.get(ruleId) ?? [],
        }),
        message,
        // `uid` on the report is the event's, so the field comes from the message.
        targetId: (TRAILING_TARGET_PATTERN.exec(message) ??
            MANDATORY_TARGET_PATTERN.exec(message))?.[1],
    }
}

export type ParseOptions = {
    status: EventStatus
    /** Rule id to the action types it declares, from the program metadata. */
    actionTypesByRule?: ReadonlyMap<string, readonly string[]>
}

/**
 * Maps a tracker importer validation report to the rule entries the summary
 * compares against the simulation. Everything that is not a rule-generated
 * report (e.g. E1302 invalid value) is returned as `otherErrors`.
 */
export function parseRuleValidationReport(
    body: unknown,
    options: ParseOptions
): ParsedRuleValidationReport {
    const report = findValidationReport(body)
    const entries: ServerReportEntry[] = []
    const otherErrors: OtherImportError[] = []

    const collect = (items: ReportItem[] = [], kind: ReportKind) => {
        for (const item of items) {
            const entry = toEntry(item, kind, options)
            if (entry) {
                entries.push(entry)
            } else if (kind === ReportKind.ERROR && item.message) {
                otherErrors.push({
                    code: item.errorCode,
                    message: item.message,
                })
            }
        }
    }
    collect(report?.errorReports, ReportKind.ERROR)
    collect(report?.warningReports, ReportKind.WARNING)

    return { verification: { entries }, otherErrors }
}
